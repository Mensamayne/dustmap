import { describe, expect, it } from "vitest";
import {
  hasGeneratedHeader,
  isGeneratedPath,
  isImportOnlyFragment,
  isLowConfidenceCloneFragment,
  isZodSchemaFragment,
  shouldScanForJscpd,
} from "./noise.js";

describe("jscpd noise", () => {
  it("flags import-only blocks as low-confidence noise", () => {
    const fragment = `
import { a } from "./a";
import { b } from "./b";
import { c } from "./c";
import { d } from "./d";
export { a, b, c, d } from "./barrel";
`.trim();
    expect(isImportOnlyFragment(fragment)).toBe(true);
    expect(isLowConfidenceCloneFragment(fragment)).toBe(true);
  });

  it("flags Zod schema blocks as low-confidence noise", () => {
    const fragment = `
export const UserSchema = z.object({
  id: z.string(),
  age: z.number().optional(),
  tags: z.array(z.string()),
});
`.trim();
    expect(isZodSchemaFragment(fragment)).toBe(true);
    expect(isLowConfidenceCloneFragment(fragment)).toBe(true);
  });

  it("does not flag real logic as import/zod noise", () => {
    const fragment = `
export function computeScore(items: number[]): number {
  let total = 0;
  for (const item of items) {
    total += item * 2;
  }
  return total;
}
`.trim();
    expect(isImportOnlyFragment(fragment)).toBe(false);
    expect(isZodSchemaFragment(fragment)).toBe(false);
  });

  it("skips generated paths and headers", () => {
    expect(isGeneratedPath("src/api.gen.ts")).toBe(true);
    expect(hasGeneratedHeader("// @generated by protoc\nexport const x = 1;\n")).toBe(true);
    expect(
      shouldScanForJscpd("src/api.gen.ts", "source", "export const x = 1", {
        skipTests: true,
        skipFixtures: true,
        skipGenerated: true,
      }),
    ).toBe(false);
    expect(
      shouldScanForJscpd("src/a.test.ts", "test", "export {}", {
        skipTests: true,
        skipFixtures: true,
        skipGenerated: true,
      }),
    ).toBe(false);
    expect(
      shouldScanForJscpd("src/a.ts", "source", "export const x = 1", {
        skipTests: true,
        skipFixtures: true,
        skipGenerated: true,
      }),
    ).toBe(true);
  });
});
