/**
 * Noise policy for copy-paste clusters: skip test/fixture/generated inputs by default, and demote
 * clusters that are only imports or Zod-shaped schemas to low confidence.
 */

import type { FileRoleType } from "@dustmap/contract";

export type JscpdNoiseOptions = {
  /** Skip `test` role files (default true). */
  skipTests: boolean;
  /** Skip `fixture` role files (default true). */
  skipFixtures: boolean;
  /** Skip paths matching `*.gen.*` and files whose header says generated (default true). */
  skipGenerated: boolean;
};

export const DEFAULT_JSCPD_NOISE: JscpdNoiseOptions = {
  skipTests: true,
  skipFixtures: true,
  skipGenerated: true,
};

const BLOCKED_ROLES = new Set<FileRoleType>([
  "generated",
  "vendored",
  "minified",
  "oversized",
]);

const GEN_PATH = /(^|\/)[^/]*\.gen\.[^/]+$/i;
const GENERATED_HEADER =
  /(?:^|\n)\s*(?:\/\/|#|\*|\/\*)\s*(?:@generated|code generated|this file (?:is|was) (?:auto-)?generated|generated by)\b/i;

export function parseJscpdNoiseOptions(raw: Record<string, unknown> | undefined): JscpdNoiseOptions {
  const src = raw ?? {};
  return {
    skipTests: typeof src.skipTests === "boolean" ? src.skipTests : DEFAULT_JSCPD_NOISE.skipTests,
    skipFixtures:
      typeof src.skipFixtures === "boolean" ? src.skipFixtures : DEFAULT_JSCPD_NOISE.skipFixtures,
    skipGenerated:
      typeof src.skipGenerated === "boolean" ? src.skipGenerated : DEFAULT_JSCPD_NOISE.skipGenerated,
  };
}

/** True when the path looks like a generated artefact (`foo.gen.ts`). */
export function isGeneratedPath(repoRelativePosix: string): boolean {
  return GEN_PATH.test(repoRelativePosix);
}

/** True when the file header claims the contents were generated. */
export function hasGeneratedHeader(text: string): boolean {
  const head = text.slice(0, 800);
  return GENERATED_HEADER.test(head);
}

/**
 * Decide whether a scanned file should be fed to jscpd given its role and noise options.
 * Blocked roles are never scanned; test/fixture/generated skips are configurable.
 */
export function shouldScanForJscpd(
  repoRelativePosix: string,
  role: FileRoleType | undefined,
  text: string | undefined,
  opts: JscpdNoiseOptions,
): boolean {
  if (!role || BLOCKED_ROLES.has(role)) return false;
  if (opts.skipTests && role === "test") return false;
  if (opts.skipFixtures && role === "fixture") return false;
  if (opts.skipGenerated) {
    if (role === "generated" || isGeneratedPath(repoRelativePosix)) return false;
    if (text !== undefined && hasGeneratedHeader(text)) return false;
  }
  return role === "source" || (!opts.skipTests && role === "test") || (!opts.skipFixtures && role === "fixture");
}

function nonEmptyLines(fragment: string): string[] {
  return fragment
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l.length > 0 && !l.startsWith("//") && l !== "/*" && l !== "*/");
}

/** Import / re-export lines that carry no logic. */
export function isImportOnlyFragment(fragment: string): boolean {
  const lines = nonEmptyLines(fragment);
  if (lines.length < 2) return false;
  const importLike = lines.filter(
    (l) =>
      /^import\s/.test(l) ||
      /^export\s+\*\s+from\s/.test(l) ||
      /^export\s+\{[^}]*\}\s*from\s/.test(l) ||
      /^export\s+type\s+\{[^}]*\}\s*from\s/.test(l),
  );
  return importLike.length / lines.length >= 0.8;
}

/** Zod schema declarations (and similar `z.*` chains) without other logic. */
export function isZodSchemaFragment(fragment: string): boolean {
  const lines = nonEmptyLines(fragment);
  if (lines.length < 2) return false;
  const zodLike = lines.filter(
    (l) =>
      /\bz\.(object|string|number|boolean|array|enum|union|literal|record|optional|nullable|infer)\b/.test(
        l,
      ) ||
      /\bSchema\s*[:=]/.test(l) ||
      /^export\s+const\s+\w+Schema\b/.test(l),
  );
  return zodLike.length / lines.length >= 0.6;
}

/** Clusters that are only imports or Zod schemas must not be high confidence. */
export function isLowConfidenceCloneFragment(fragment: string): boolean {
  return isImportOnlyFragment(fragment) || isZodSchemaFragment(fragment);
}
