/**
 * File roles: decide what each scanned file actually is (source, test, generated, vendored, …).
 * Generic rules only, in priority order:
 *   1. git attributes the user already maintains for GitHub Linguist (`linguist-generated`,
 *      `linguist-vendored`, `linguist-documentation`) — one `git check-attr --stdin` call per scan;
 *   2. role globs from the user's config (`classify.*`);
 *   3. path conventions (.d.ts, test/fixture dirs and suffixes, vendor dirs, *.min.*);
 *   4. size above `classify.maxFileBytes` → `oversized`, decided from stat, content never read;
 *   5. content shape: generated-file header comment, or machine-shaped lines (minified / inlined data).
 * Every role carries a reason so the report can say why a file was skipped.
 */
import { execFileSync } from "node:child_process";
import { Minimatch } from "minimatch";
import type { FileRoleType } from "@dustmap/contract";
import type { ClassifyConfig } from "../config/schema.js";

export type Classification = { role: FileRoleType; reason: string };

const TEST_DIRS = new Set(["__tests__", "test", "tests", "e2e", "__snapshots__"]);
const FIXTURE_DIRS = new Set(["fixtures", "fixture", "__fixtures__", "__mocks__", "mocks", "testdata", "test-support"]);
const VENDOR_DIRS = new Set(["vendor", "third_party", "third-party"]);
const TEST_SUFFIX = /\.(test|spec|e2e)\.[cm]?[jt]sx?$/;
const DECLARATION = /\.d\.[cm]?ts$/;
const MINIFIED_NAME = /\.min\.[cm]?js$/;

const GENERATED_MARK = /@generated\b|\bauto-?generated\b|\bdo not edit\b|\bgenerated by\b|\bthis file (?:was|is) (?:automatically )?generated\b/i;
const COMMENT_LINE = /^\s*(?:\/\/|\/\*|\*|#!?)/;

/** Longest single line that still reads as hand-written code. */
const MAX_HUMAN_LINE = 2000;
/** Average characters per line above which a file is machine-shaped. */
const MAX_HUMAN_AVG_LINE = 250;

type AttrRole = "generated" | "vendored" | "documentation";

/** Linguist attributes set for the given paths (POSIX, relative to repoRoot). Empty outside git. */
export function linguistAttributes(repoRoot: string, files: readonly string[]): Map<string, AttrRole> {
  const out = new Map<string, AttrRole>();
  if (!files.length) return out;
  let raw: string;
  try {
    raw = execFileSync(
      "git",
      ["check-attr", "-z", "--stdin", "linguist-generated", "linguist-vendored", "linguist-documentation"],
      { cwd: repoRoot, input: files.join("\0"), encoding: "utf8", maxBuffer: 256 * 1024 * 1024, stdio: ["pipe", "pipe", "ignore"] },
    );
  } catch {
    return out; // not a git work tree: no attributes to honour
  }
  const parts = raw.split("\0");
  for (let i = 0; i + 2 < parts.length; i += 3) {
    const [file, attr, value] = [parts[i]!, parts[i + 1]!, parts[i + 2]!];
    if (value !== "set" && value !== "true") continue;
    const role: AttrRole | null =
      attr === "linguist-generated" ? "generated" : attr === "linguist-vendored" ? "vendored" : attr === "linguist-documentation" ? "documentation" : null;
    if (role && !out.has(file)) out.set(file, role);
  }
  return out;
}

export type PathClassifier = (rel: string) => Classification | null;

/** Rules 2–3: config globs, then path conventions. Null = decide from size/content. */
export function pathClassifier(cfg: ClassifyConfig): PathClassifier {
  const opts = { dot: true };
  const globs: Array<[FileRoleType, Minimatch[]]> = [
    ["generated", cfg.generated.map((g) => new Minimatch(g, opts))],
    ["vendored", cfg.vendored.map((g) => new Minimatch(g, opts))],
    ["test", cfg.test.map((g) => new Minimatch(g, opts))],
    ["fixture", cfg.fixture.map((g) => new Minimatch(g, opts))],
  ];
  return (rel) => {
    for (const [role, matchers] of globs) {
      const hit = matchers.find((m) => m.match(rel));
      if (hit) return { role, reason: `config classify.${role}: ${hit.pattern}` };
    }
    if (DECLARATION.test(rel)) return { role: "declaration", reason: "type declaration file" };
    const dirs = rel.split("/").slice(0, -1);
    if (dirs.some((d) => VENDOR_DIRS.has(d))) return { role: "vendored", reason: "inside a vendor directory" };
    if (MINIFIED_NAME.test(rel)) return { role: "minified", reason: "*.min.* file name" };
    if (TEST_SUFFIX.test(rel) || dirs.some((d) => TEST_DIRS.has(d))) return { role: "test", reason: "test file or directory" };
    if (dirs.some((d) => FIXTURE_DIRS.has(d))) return { role: "fixture", reason: "fixture or mock directory" };
    return null;
  };
}

/** Rule 5: decide from file text. */
export function classifyContent(text: string): Classification {
  const head = text.split("\n", 15).filter((l) => COMMENT_LINE.test(l)).join("\n");
  if (GENERATED_MARK.test(head)) return { role: "generated", reason: "generated-file header comment" };
  const lines = text.split("\n");
  let longest = 0;
  for (const l of lines) if (l.length > longest) longest = l.length;
  if (longest > MAX_HUMAN_LINE) return { role: "minified", reason: `line of ${longest} characters` };
  const avg = text.length / Math.max(lines.length, 1);
  if (text.length > 2000 && avg > MAX_HUMAN_AVG_LINE) return { role: "minified", reason: `${Math.round(avg)} characters per line on average` };
  return { role: "source", reason: "hand-written code" };
}

/** All rules for one file. `text` is omitted for files decided by size. */
export function classifyFile(
  rel: string,
  sizeBytes: number,
  readText: () => string,
  cfg: ClassifyConfig,
  attrs: ReadonlyMap<string, AttrRole>,
  byPath: PathClassifier,
): Classification {
  const attr = attrs.get(rel);
  if (attr === "generated") return { role: "generated", reason: ".gitattributes linguist-generated" };
  if (attr === "vendored") return { role: "vendored", reason: ".gitattributes linguist-vendored" };
  if (attr === "documentation") return { role: "fixture", reason: ".gitattributes linguist-documentation" };
  const fromPath = byPath(rel);
  if (fromPath) return fromPath;
  if (sizeBytes > cfg.maxFileBytes) return { role: "oversized", reason: `${sizeBytes} bytes (limit ${cfg.maxFileBytes})` };
  return classifyContent(readText());
}
