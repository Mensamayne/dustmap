import { describe, expect, it } from "vitest";
import { ClassifyConfig } from "../config/schema.js";
import { classifyContent, classifyFile, pathClassifier } from "./classify.js";

const cfg = ClassifyConfig.parse({});
const byPath = pathClassifier(cfg);
const noAttrs = new Map<string, "generated" | "vendored" | "documentation">();
const classify = (rel: string, text: string, size = text.length, attrs = noAttrs) =>
  classifyFile(rel, size, () => text, cfg, attrs, byPath).role;

describe("file roles", () => {
  it("path conventions", () => {
    expect(classify("src/types.d.ts", "")).toBe("declaration");
    expect(classify("src/a.test.ts", "")).toBe("test");
    expect(classify("web/__tests__/x.ts", "")).toBe("test");
    expect(classify("pkg/fixtures/sample.ts", "")).toBe("fixture");
    expect(classify("ui/vendor/three/three.js", "")).toBe("vendored");
    expect(classify("public/lib.min.js", "")).toBe("minified");
    expect(classify("src/contest.ts", "export const a = 1;\n")).toBe("source");
  });

  it("generated header only counts inside leading comments", () => {
    expect(classifyContent("// @generated by tool\nexport const a = 1;\n").role).toBe("generated");
    expect(classifyContent("/* This file was automatically generated. DO NOT EDIT. */\n").role).toBe("generated");
    expect(classifyContent("export const msg = 'ids are generated by the server';\n").role).toBe("source");
  });

  it("machine-shaped text is minified", () => {
    expect(classifyContent(`var a=${"1,".repeat(1500)}1;\n`).role).toBe("minified");
    const wide = Array.from({ length: 20 }, () => "x".repeat(400)).join("\n");
    expect(classifyContent(wide).role).toBe("minified");
    const human = Array.from({ length: 200 }, (_, i) => `export const v${i} = ${i};`).join("\n");
    expect(classifyContent(human).role).toBe("source");
  });

  it("oversized is decided from size without reading the file", () => {
    let read = false;
    const role = classifyFile("src/big.ts", cfg.maxFileBytes + 1, () => ((read = true), ""), cfg, noAttrs, byPath).role;
    expect(role).toBe("oversized");
    expect(read).toBe(false);
  });

  it("git attributes and config globs win over heuristics", () => {
    const attrs = new Map([["src/hand.ts", "generated" as const]]);
    expect(classify("src/hand.ts", "export const a = 1;\n", 20, attrs)).toBe("generated");
    const custom = ClassifyConfig.parse({ vendored: ["design-kit/**"] });
    expect(classifyFile("design-kit/a.ts", 10, () => "x", custom, noAttrs, pathClassifier(custom)).role).toBe("vendored");
  });
});
